"""
ByteVault Dashboard & HTML Report Generator
Generates comprehensive visual HTML and Markdown status reports for backups.
"""

from datetime import datetime
import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from automated_backup.config import BackupConfig
from automated_backup.engine import BackupEngine
from automated_backup.reporter import format_bytes


class DashboardGenerator:
    """Creates standalone visual HTML dashboards and Markdown reports."""

    def __init__(self, config: BackupConfig):
        self.config = config
        self.engine = BackupEngine(config)

    def generate_markdown_report(self) -> str:
        """Generate a formatted Markdown report of the backup vault status."""
        snapshots = self.engine.get_existing_snapshots()
        total_snaps = len(snapshots)
        total_archive_size = sum(s.get("archive_size_bytes", 0) for s in snapshots)
        latest_snap = snapshots[-1] if snapshots else None

        md = []
        md.append(f"# ByteVault Status Report: `{self.config.task_name}`\n")
        md.append(f"**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        md.append("## Overview Metrics\n")
        md.append(f"- **Total Recorded Snapshots:** {total_snaps}")
        md.append(f"- **Total Storage Consumed:** {format_bytes(total_archive_size)}")
        md.append(f"- **Configured Retention:** {self.config.retention_count} snapshots (max {self.config.retention_days or 'unlimited'} days)")
        md.append(f"- **Latest Backup:** {latest_snap.get('snapshot_id') if latest_snap else 'None'}\n")

        md.append("## Snapshot History\n")
        md.append("| Snapshot ID | Type | Timestamp | Files | Archive Size | Base Snapshot |")
        md.append("|---|---|---|---|---|---|")
        for s in reversed(snapshots):
            base = s.get("base_snapshot_id") or "None (Full)"
            ts = s.get("timestamp", "N/A")[:19].replace("T", " ")
            md.append(
                f"| `{s.get('snapshot_id')}` | **{s.get('type', 'N/A').upper()}** | "
                f"{ts} | {s.get('files_packed_count', 0)} | "
                f"{format_bytes(s.get('archive_size_bytes', 0))} | `{base}` |"
            )
        md.append("\n---\n*Report generated by ByteVault Automated Backup System*\n")
        return "\n".join(md)

    def generate_html_report(self) -> str:
        """Generate a rich, standalone modern HTML dashboard."""
        snapshots = self.engine.get_existing_snapshots()
        total_snaps = len(snapshots)
        total_archive_size = sum(s.get("archive_size_bytes", 0) for s in snapshots)
        total_raw_bytes = 0
        if snapshots:
            # sum unique or latest raw sizes
            latest_state = snapshots[-1].get("full_state", snapshots[-1].get("included_files", {}))
            total_raw_bytes = sum(item.get("size", 0) for item in latest_state.values())

        latest_snap = snapshots[-1] if snapshots else None
        latest_time = latest_snap.get("timestamp", "N/A")[:19].replace("T", " ") if latest_snap else "N/A"

        # Calculate space savings
        saved_bytes = max(0, total_raw_bytes - (latest_snap.get("archive_size_bytes", 0) if latest_snap else 0))

        # Build table rows
        rows = []
        for s in reversed(snapshots):
            snap_type = s.get("type", "full").upper()
            badge_class = "badge-full" if snap_type == "FULL" else "badge-inc"
            ts = s.get("timestamp", "N/A")[:19].replace("T", " ")
            base = s.get("base_snapshot_id") or "—"
            sha = s.get("archive_sha256", "N/A")
            sha_short = f"{sha[:12]}..." if sha != "N/A" else "—"

            changes = s.get("changes_summary", {})
            diff_summary = f"+{changes.get('added', 0)} / ~{changes.get('modified', 0)} / -{changes.get('deleted', 0)}"

            rows.append(f"""
            <tr>
              <td><code>{s.get('snapshot_id')}</code></td>
              <td><span class="badge {badge_class}">{snap_type}</span></td>
              <td>{ts}</td>
              <td>{s.get('files_packed_count', 0)}</td>
              <td>{format_bytes(s.get('archive_size_bytes', 0))}</td>
              <td><span class="tag">{diff_summary}</span></td>
              <td><code>{base}</code></td>
              <td title="{sha}"><code>{sha_short}</code></td>
            </tr>
            """)

        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>ByteVault Dashboard - {self.config.task_name}</title>
  <style>
    :root {{
      --bg: #0f172a;
      --card-bg: #1e293b;
      --border: #334155;
      --text: #f8fafc;
      --text-muted: #94a3b8;
      --accent: #38bdf8;
      --green: #22c55e;
      --purple: #a855f7;
    }}
    * {{ box-sizing: border-box; margin: 0; padding: 0; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; }}
    body {{ background: var(--bg); color: var(--text); padding: 2.5rem 1.5rem; line-height: 1.5; }}
    .container {{ max-width: 1200px; margin: 0 auto; }}
    header {{ display: flex; justify-content: space-between; align-items: center; margin-bottom: 2rem; border-bottom: 1px solid var(--border); padding-bottom: 1.5rem; }}
    h1 {{ font-size: 1.8rem; font-weight: 700; color: #fff; }}
    h1 span {{ color: var(--accent); }}
    .timestamp {{ color: var(--text-muted); font-size: 0.9rem; }}
    .grid {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(220px, 1fr)); gap: 1.25rem; margin-bottom: 2.5rem; }}
    .card {{ background: var(--card-bg); border: 1px solid var(--border); border-radius: 12px; padding: 1.25rem; }}
    .card-title {{ font-size: 0.85rem; text-transform: uppercase; letter-spacing: 0.05em; color: var(--text-muted); margin-bottom: 0.5rem; }}
    .card-value {{ font-size: 1.8rem; font-weight: 700; color: #fff; }}
    .badge {{ display: inline-block; padding: 0.25rem 0.6rem; border-radius: 6px; font-size: 0.75rem; font-weight: 600; text-transform: uppercase; }}
    .badge-full {{ background: rgba(56, 189, 248, 0.15); color: #38bdf8; border: 1px solid rgba(56, 189, 248, 0.3); }}
    .badge-inc {{ background: rgba(168, 85, 247, 0.15); color: #c084fc; border: 1px solid rgba(168, 85, 247, 0.3); }}
    .tag {{ background: #334155; padding: 0.2rem 0.5rem; border-radius: 4px; font-size: 0.8rem; }}
    table {{ width: 100%; border-collapse: collapse; background: var(--card-bg); border-radius: 12px; overflow: hidden; border: 1px solid var(--border); }}
    th, td {{ padding: 0.85rem 1rem; text-align: left; font-size: 0.9rem; border-bottom: 1px solid var(--border); }}
    th {{ background: #1a2234; color: var(--text-muted); font-weight: 600; text-transform: uppercase; font-size: 0.75rem; }}
    tr:hover {{ background: rgba(255, 255, 255, 0.02); }}
    code {{ font-family: ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace; font-size: 0.85rem; color: #e2e8f0; }}
    footer {{ text-align: center; margin-top: 3rem; color: var(--text-muted); font-size: 0.85rem; }}
  </style>
</head>
<body>
  <div class="container">
    <header>
      <div>
        <h1>ByteVault <span>Dashboard</span></h1>
        <p class="timestamp">Task Profile: <strong>{self.config.task_name}</strong> | Destination: <code>{self.config.backup_dest}</code></p>
      </div>
      <div class="timestamp">
        Report Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
      </div>
    </header>

    <div class="grid">
      <div class="card">
        <div class="card-title">Total Snapshots</div>
        <div class="card-value">{total_snaps}</div>
      </div>
      <div class="card">
        <div class="card-title">Vault Storage Used</div>
        <div class="card-value">{format_bytes(total_archive_size)}</div>
      </div>
      <div class="card">
        <div class="card-title">Uncompressed Live Size</div>
        <div class="card-value">{format_bytes(total_raw_bytes)}</div>
      </div>
      <div class="card">
        <div class="card-title">Storage Compression Saving</div>
        <div class="card-value" style="color: var(--green);">{format_bytes(saved_bytes)}</div>
      </div>
      <div class="card">
        <div class="card-title">Latest Backup</div>
        <div class="card-value" style="font-size: 1.1rem; padding-top: 0.5rem;">{latest_time}</div>
      </div>
    </div>

    <h2 style="margin-bottom: 1rem; font-size: 1.3rem;">Snapshot History & Chain</h2>
    <table>
      <thead>
        <tr>
          <th>Snapshot ID</th>
          <th>Type</th>
          <th>Created</th>
          <th>Packed Files</th>
          <th>Archive Size</th>
          <th>Changes (+/~/-)</th>
          <th>Base Snapshot</th>
          <th>SHA-256 Checksum</th>
        </tr>
      </thead>
      <tbody>
        {"".join(rows) if rows else '<tr><td colspan="8" style="text-align: center; padding: 2rem;">No snapshots recorded yet.</td></tr>'}
      </tbody>
    </table>

    <footer>
      ByteVault Autonomous Backup System &bull; Cryptographically Verified &bull; Python Standard Library
    </footer>
  </div>
</body>
</html>
"""
        return html

    def export(self, output_path: Path, fmt: str = "html") -> Path:
        """Save report to destination path."""
        path = Path(output_path).resolve()
        path.parent.mkdir(parents=True, exist_ok=True)
        content = self.generate_html_report() if fmt.lower() == "html" else self.generate_markdown_report()
        path.write_text(content, encoding="utf-8")
        return path
